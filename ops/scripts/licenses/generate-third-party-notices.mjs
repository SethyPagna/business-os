import { createHash } from 'node:crypto'
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const LOCKED_PACKAGES = ['frontend', 'cloudflare']
const OUTPUT_PATH = ['frontend', 'public', 'THIRD_PARTY_NOTICES.txt']
const NOTICE_FILE = /^(licen[sc]e|copying|notice)([-_.].*)?$/i
const CODE_FILE = /\.(?:[cm]?[jt]s|json|map)$/i
const RULE = '-'.repeat(72)

const ALLOWED_LICENSES = new Set([
  'MIT',
  'ISC',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'OFL-1.1',
  'CC0-1.0',
  'Unlicense',
  '(Unlicense OR Apache-2.0)',
  'MIT OR Apache-2.0',
])

const BLOCKED_PACKAGES = {
  '@ffmpeg/core': 'its wasm is built with --enable-gpl --enable-nonfree although the package declares MIT',
  '@ffmpeg/ffmpeg': 'it downloads the GPL and nonfree @ffmpeg/core build from a public CDN at runtime',
}

const argv = process.argv.slice(2)
const rootFlag = argv.indexOf('--root')
const root = resolve(rootFlag >= 0 ? argv[rootFlag + 1] : join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..'))
const outputFile = join(root, ...OUTPUT_PATH)
const checkOnly = argv.includes('--check')

const normalise = (text) => text.replace(/^﻿/, '').replace(/\r\n?/g, '\n').trim()
const byId = (left, right) => (left.id < right.id ? -1 : left.id > right.id ? 1 : 0)

function readLicenseText(dir, license) {
  const texts = readdirSync(dir)
    .filter((name) => NOTICE_FILE.test(name) && !CODE_FILE.test(name) && statSync(join(dir, name)).isFile())
    .sort()
    .map((name) => normalise(readFileSync(join(dir, name), 'utf8')))
    .filter(Boolean)
  return texts.length ? texts.join('\n\n') : `${license} (declared in package.json; the package ships no licence file)`
}

function collectPackages() {
  const found = new Map()
  const problems = []
  for (const workspace of LOCKED_PACKAGES) {
    const lock = JSON.parse(readFileSync(join(root, workspace, 'package-lock.json'), 'utf8'))
    for (const [key, meta] of Object.entries(lock.packages)) {
      if (!key || meta.dev || meta.devOptional) continue
      const name = key.replace(/^.*node_modules\//, '')
      const id = `${name}@${meta.version}`
      if (found.has(id)) continue
      const license = meta.license || 'MISSING'
      if (BLOCKED_PACKAGES[name]) problems.push(`${id}: blocked, ${BLOCKED_PACKAGES[name]}`)
      if (!ALLOWED_LICENSES.has(license)) problems.push(`${id}: licence "${license}" is not on the allow list`)
      const dir = join(root, workspace, key)
      if (!existsSync(join(dir, 'package.json'))) {
        if (!meta.optional) problems.push(`${id}: ${workspace}/${key} is not installed; run npm ci in ${workspace}`)
        continue
      }
      const installed = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).version
      if (installed !== meta.version) {
        problems.push(`${id}: ${workspace}/${key} has ${installed} installed; run npm ci in ${workspace}`)
        continue
      }
      found.set(id, { id, license, text: readLicenseText(dir, license) })
    }
  }
  return { packages: [...found.values()].sort(byId), problems }
}

function renderNotices(packages) {
  const groups = new Map()
  for (const entry of packages) {
    const hash = createHash('sha256').update(entry.text).digest('hex')
    if (!groups.has(hash)) groups.set(hash, { text: entry.text, members: [] })
    groups.get(hash).members.push(`${entry.id} (${entry.license})`)
  }
  const lines = [
    'Third-party notices',
    '',
    'Business OS includes the open-source components listed below. Each is used under its own licence, reproduced in full under the packages it covers.',
    'Generated by ops/scripts/licenses/generate-third-party-notices.mjs from frontend/package-lock.json and cloudflare/package-lock.json (runtime dependencies only). Do not edit by hand.',
    '',
    `${packages.length} packages, ${groups.size} distinct licence texts.`,
    '',
  ]
  for (const group of groups.values()) lines.push(RULE, ...group.members, RULE, '', group.text, '')
  return lines.join('\n')
}

const { packages, problems } = collectPackages()
const notices = renderNotices(packages)

if (checkOnly) {
  const committed = existsSync(outputFile) ? normalise(readFileSync(outputFile, 'utf8')) : ''
  if (committed !== normalise(notices)) problems.push(`${OUTPUT_PATH.join('/')} is out of date; run npm run licenses:notices in frontend and commit the result`)
}

if (problems.length) {
  console.error(problems.map((problem) => `- ${problem}`).join('\n'))
  process.exit(1)
}

if (checkOnly) {
  console.log(`third-party notices are current: ${packages.length} packages`)
} else {
  writeFileSync(outputFile, notices)
  console.log(`wrote ${OUTPUT_PATH.join('/')}: ${packages.length} packages`)
}
