const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const source = fs.readFileSync(path.join(__dirname, '../src/lib/backup.ts'), 'utf8')
const list = source.match(/export const BACKUP_TABLES = \[([\s\S]*?)\] as const/)[1]
const tables = [...list.matchAll(/'([^']+)'/g)].map(match => match[1])
for (const table of ['customer_receivables', 'supplier_invoices', 'undo_snapshots', 'sale_amendments', 'sale_write_revisions', 'sale_bulk_operations', 'sale_bulk_members']) assert(tables.includes(table), `${table} must survive backup/restore`)
assert(tables.indexOf('customer_receivables') > tables.indexOf('customers'))
assert(tables.indexOf('supplier_invoices') > tables.indexOf('suppliers'))
assert(tables.indexOf('undo_snapshots') > tables.indexOf('action_history'))
assert.equal(new Set(tables).size, tables.length)
assert(tables.indexOf('sale_bulk_operations') > tables.indexOf('undo_snapshots'))
assert(tables.indexOf('sale_bulk_members') > tables.indexOf('sale_bulk_operations'))
const {DatabaseSync}=require('node:sqlite')
const db=new DatabaseSync(':memory:')
db.exec("CREATE TABLE system_flags(key TEXT PRIMARY KEY,value TEXT); CREATE TABLE sale_amendments(id INTEGER PRIMARY KEY); INSERT INTO sale_amendments VALUES(1);")
const migration=fs.readFileSync(path.join(__dirname,'../migrations/0121_sale_amendment_restore_guard.sql'),'utf8')
assert(!migration.includes('\r'),'Trigger SQL must remain LF-only')
db.exec(migration)
assert.throws(()=>db.exec('DELETE FROM sale_amendments'),/immutable/)
db.exec(`INSERT INTO system_flags VALUES('maintenance','{"mode":"backup"}')`)
assert.throws(()=>db.exec('DELETE FROM sale_amendments'),/immutable/)
db.exec(`UPDATE system_flags SET value='{"mode":"restore"}'`)
db.exec('DELETE FROM sale_amendments')
assert.equal(db.prepare('SELECT COUNT(*) n FROM sale_amendments').get().n,0)
db.close()
console.log('PASS: historical finance and durable reversal backup coverage')
