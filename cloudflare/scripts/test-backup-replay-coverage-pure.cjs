const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const source = fs.readFileSync(path.join(__dirname, '../src/lib/backup.ts'), 'utf8')
const list = source.match(/export const BACKUP_TABLES = \[([\s\S]*?)\] as const/)[1]
const tables = [...list.matchAll(/'([^']+)'/g)].map(match => match[1])
for (const table of ['customer_receivables', 'supplier_invoices', 'undo_snapshots', 'sale_amendments', 'sale_write_revisions', 'sale_mutation_receipts', 'sale_mutation_members', 'sale_bulk_operations', 'sale_bulk_members']) assert(tables.includes(table), `${table} must survive backup/restore`)
for (const table of ['sale_incident_recovery_receipts', 'sale_incident_recovery_members']) assert(tables.includes(table), `${table} must survive backup/restore`)
assert(tables.indexOf('customer_receivables') > tables.indexOf('customers'))
assert(tables.indexOf('supplier_invoices') > tables.indexOf('suppliers'))
assert(tables.indexOf('undo_snapshots') > tables.indexOf('action_history'))
assert.equal(new Set(tables).size, tables.length)
assert(tables.indexOf('sale_bulk_operations') > tables.indexOf('undo_snapshots'))
assert(tables.indexOf('sale_bulk_members') > tables.indexOf('sale_bulk_operations'))
assert(tables.indexOf('sale_mutation_receipts') > tables.indexOf('action_history'))
assert(tables.indexOf('sale_mutation_members') > tables.indexOf('sale_mutation_receipts'))
assert(!tables.includes('sale_mutation_guards'), 'transient sale mutation guards are not durable backup state')
assert(tables.indexOf('sale_incident_recovery_receipts') > tables.indexOf('action_history'))
assert(tables.indexOf('sale_incident_recovery_members') > tables.indexOf('sale_incident_recovery_receipts'))
assert(!tables.includes('sale_incident_recovery_guards'), 'transient incident recovery guards are not durable backup state')
for (const table of ['return_write_revisions', 'return_bulk_operations', 'return_bulk_members', 'return_mutation_receipts', 'return_create_receipts', 'stock_session_revisions', 'stock_session_operations', 'stock_session_members']) assert(tables.includes(table), `${table} must survive backup/restore`)
assert(tables.indexOf('return_mutation_receipts') > tables.indexOf('returns'))
assert(tables.indexOf('return_create_receipts') > tables.indexOf('returns'))
assert(!tables.includes('return_create_guards'))
assert(tables.indexOf('stock_session_operations') > tables.indexOf('undo_snapshots'))
assert(tables.indexOf('stock_session_operations') > tables.indexOf('inventory_movements'))
assert(tables.indexOf('stock_session_members') > tables.indexOf('stock_session_operations'))
assert(!tables.includes('stock_session_guards'), 'ephemeral guards are not durable backup state')
for (const table of ['product_conflict_merge_runs', 'product_conflict_merge_run_cases']) assert(tables.includes(table), `${table} must survive backup/restore`)
assert(tables.indexOf('product_conflict_merge_runs') > tables.indexOf('products'))
assert(tables.indexOf('product_conflict_merge_run_cases') > tables.indexOf('product_conflict_merge_runs'))
assert(tables.indexOf('product_conflict_merge_run_cases') > tables.indexOf('action_history'))
for (const table of ['product_conflict_action_reviews', 'product_conflict_action_groups', 'product_conflict_action_group_members', 'product_remove_operations']) assert(tables.includes(table), `${table} must survive backup/restore`)
assert(tables.indexOf('product_conflict_action_reviews') > tables.indexOf('undo_snapshots'))
assert(tables.indexOf('product_conflict_action_groups') > tables.indexOf('product_conflict_action_reviews'))
assert(tables.indexOf('product_conflict_action_group_members') > tables.indexOf('product_conflict_action_groups'))
assert(tables.indexOf('product_remove_operations') > tables.indexOf('product_conflict_action_reviews'))
const replayBundleList = source.match(/export const SALE_REPLAY_RESTORE_BUNDLE = \[([\s\S]*?)\] as const/)[1]
const replayBundleTables = [...replayBundleList.matchAll(/'([^']+)'/g)].map(match => match[1])
for (const table of [
  'pending_actions',
  'product_conflict_action_reviews',
  'product_conflict_action_groups',
  'product_conflict_action_group_members',
  'product_remove_operations',
  'product_conflict_merge_runs',
  'product_conflict_merge_run_cases',
]) assert(replayBundleTables.includes(table), `${table} must accompany product-bearing Sales replay backups`)
const resetSource = fs.readFileSync(path.join(__dirname, '../src/lib/coreDataInvariants.ts'), 'utf8')
const resetList = resetSource.match(/export const FACTORY_RESET_TABLES = \[([\s\S]*?)\n\]/)[1]
const resetTables = [...resetList.matchAll(/'([^']+)'/g)].map(match => match[1])
assert(resetTables.indexOf('sale_mutation_members') > -1)
assert(resetTables.indexOf('sale_mutation_members') < resetTables.indexOf('sale_mutation_receipts'))
assert(resetTables.indexOf('sale_mutation_receipts') < resetTables.indexOf('action_history'))
assert(resetTables.includes('sale_mutation_guards'))
assert(resetTables.indexOf('sale_incident_recovery_members') > -1)
assert(resetTables.indexOf('sale_incident_recovery_members') < resetTables.indexOf('sale_incident_recovery_receipts'))
assert(resetTables.indexOf('sale_incident_recovery_receipts') < resetTables.indexOf('action_history'))
