const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { openDb } = require('./harness/d1compat.cjs')
const directory = path.resolve(__dirname,'../migrations')
const name = '0184_product_cost_entry_previous.sql'
const database = openDb(fs.readdirSync(directory).filter(file=>file.endsWith('.sql') && file < name).sort()
  .map(file=>fs.readFileSync(path.join(directory,file),'utf8')))
const db = database.db
db.exec("INSERT INTO product_cost_entries(product_id,cost_usd,source,user_name,baseline_batch_id,created_at) VALUES(1,3.123456,'manual','legacy',9,'2026-01-01')")
const before = db.prepare('SELECT * FROM product_cost_entries').all()
const sql = fs.readFileSync(path.join(directory,name),'utf8')
assert.equal(sql.includes('\r'),false,'migration SQL stays LF-only')
db.exec(sql)
const after = db.prepare('SELECT * FROM product_cost_entries').all()
assert.equal(after[0].previous_cost_usd,null)
assert.deepEqual(after.map(({previous_cost_usd,...old})=>old),before.map(row=>({...row})))
db.exec("INSERT INTO product_cost_entries(product_id,cost_usd,previous_cost_usd,source) VALUES(1,5,3.123456,'manual')")
const recorded = db.prepare('SELECT * FROM product_cost_entries').all()
assert.throws(()=>db.exec(sql),/duplicate column/i)
assert.deepEqual(db.prepare('SELECT * FROM product_cost_entries').all(),recorded,'raw repeat refuses without changing history')
console.log('PASS 0184 additive previous cost: legacy rows unchanged/NULL; exact historical precision; repeat refusal preserves all rows')
