// Every table the migrations create is either in lib/backup.ts BACKUP_TABLES
// or named below as a deliberate exclusion WITH its reason.
//
// Why: 0192 created stock_mutation_receipts -- the per-line idempotency guard
// for stock adjust/receive, "kept forever" -- and nobody added it to
// BACKUP_TABLES. A restore silently dropped every receipt, so a client retry
// of a stock line whose response was lost re-applied the stock delta. The
// hand-maintained list had no test that could notice a NEW table, so the next
// one would have been forgotten the same way. This test builds the real final
// schema from every migration and fails on any table nobody decided about.
//
// Adding a table? Put it in BACKUP_TABLES (dependency order: parents first),
// or add it to EXCLUDED with the reason a restore must not bring it back.
//
// Run: node scripts/test-backup-tables-completeness-pure.cjs
