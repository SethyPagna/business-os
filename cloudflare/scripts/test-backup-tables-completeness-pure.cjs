// Tables backed up but not yet restorable, each blocked on a trigger carve-out. Empty since 0268.
const UNRULED_SINCE_BASE = {}
Object.assign(UNRULED, UNRULED_SINCE_BASE)

const backupSource = fs.readFileSync(path.join(__dirname, '..', 'src', 'lib', 'backup.ts'), 'utf8')
const listMatch = backupSource.match(/export const BACKUP_TABLES = \[([\s\S]*?)\] as const/)
assert.ok(listMatch, 'BACKUP_TABLES literal not found')
const BACKUP_TABLES = [...listMatch[1].replace(/\/\/.*$/gm, '').matchAll(/'([^']+)'/g)].map((m) => m[1])

const db = new Database(':memory:')
db.pragma('foreign_keys = OFF')
for (const sql of loadAll()) db.exec(sql)
const schema = db.prepare("SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'").all()
const names = new Set(schema.map((t) => t.name))

// FTS5 virtual tables and their shadow tables are a derived search index kept
// in step with the base tables by triggers; the base rows are what is backed up.
const virtualTables = schema.filter((t) => /^CREATE VIRTUAL TABLE/i.test(t.sql || '')).map((t) => t.name)
const isDerivedIndex = (name) => virtualTables.some((v) => name === v || new RegExp(`^${v}_(config|data|docsize|idx|content)$`).test(name))

let passed = 0
const check = (name, fn) => { fn(); passed += 1; console.log(`PASS ${name}`) }

check('every migrated table is backed up or explicitly excluded with a reason', () => {
  const undecided = [...names].filter((n) => !BACKUP_TABLES.includes(n) && !(n in EXCLUDED) && !(n in UNRULED) && !isDerivedIndex(n)).sort()
  assert.deepEqual(undecided, [], `tables with no backup decision: ${undecided.join(', ')}`)
})

check('every exclusion names a real table and carries a reason; none is also backed up', () => {
  for (const [table, reason] of Object.entries({ ...EXCLUDED, ...UNRULED })) {
    assert.ok(names.has(table), `stale exclusion: ${table} is not created by any migration`)
    assert.ok(String(reason).trim().length > 5, `${table} needs a reason`)
    assert.ok(!BACKUP_TABLES.includes(table), `${table} is both backed up and excluded`)
  }
})

check('every BACKUP_TABLES entry exists in the migrated schema', () => {
  const ghosts = BACKUP_TABLES.filter((t) => !names.has(t))
  assert.deepEqual(ghosts, [], `backed up but never created: ${ghosts.join(', ')}`)
})

check('the unruled list only shrinks (base-era 19; none blocked on a trigger carve-out)', () => {
  assert.deepEqual(Object.keys(UNRULED_SINCE_BASE), [], 'a backed-up table must be restorable: carve out its triggers, do not park it')
  assert.ok(Object.keys(UNRULED).length <= 19, 'do not park new tables in UNRULED -- decide')
})

// A full restore deletes every backed-up table (plus one products update) in ONE atomic stock transaction, which
// lib/backup.ts refuses above 100 statements (stockTransactionStatementCount adds its own overhead). Past that, every
// full restore refuses at run time, so the budget is checked here: chunk the restore plan before adding more tables.
check('a full restore stays inside the 100-statement atomic limit', () => {
  const txSource = fs.readFileSync(path.join(__dirname, '..', 'src', 'lib', 'stockTransaction.ts'), 'utf8')
  const overhead = Number((txSource.match(/return businessStatements \+ (\d+)/) || [])[1])
  assert.ok(Number.isInteger(overhead), 'stockTransactionStatementCount overhead not found')
  assert.ok(backupSource.includes('if (stockTransactionStatementCount(deletes.length) > 100) throw'), 'the restore guard moved; re-check this budget')
  const statements = BACKUP_TABLES.length + 1 + overhead
  assert.ok(statements <= 100, `a full restore needs ${statements} statements; chunk the restore plan before adding tables`)
  console.log(`  restore statements ${statements}/100`)
})

console.log(`\n${passed} check(s) passed.`)
