const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const Database = require('better-sqlite3')

const dir = path.join(__dirname, '../migrations')
const file = '0154_positive_lot_activation_invariant.sql'
const sql = fs.readFileSync(path.join(dir, file), 'utf8')
const base = new Database(':memory:')
for (const name of fs.readdirSync(dir).filter(f => f.endsWith('.sql') && f < file).sort()) {
  base.exec(fs.readFileSync(path.join(dir, name), 'utf8'))
}
const schema = base.serialize()
base.close()
const apply = db => db.transaction(() => db.exec(sql))()
function fixture(migrate = true) {
  const db = new Database(schema)
  db.exec("INSERT INTO products(id,name) VALUES(900001,'Invariant product'); INSERT INTO branches(id,name) VALUES(900001,'Shop'),(900002,'Warehouse')")
  db.exec(`INSERT INTO product_batches(id,variant_product_id,batch_key,lot_code,received_at,is_active,unit_cost_usd,received_quantity,received_cost_usd,notes)
    VALUES(900001,900001,'original-receipt','original-code','2026-09-03',0,17.5,12,210,'Original receipt metadata'),
          (900002,900001,'second-receipt','second-code','2026-09-04',0,19,5,95,'Second receipt metadata')`)
  if (migrate) apply(db)
  return db
}
const lot = (db, id = 900001) => db.prepare('SELECT * FROM product_batches WHERE id=?').get(id)
const qty = db => db.prepare('SELECT batch_id,branch_id,quantity FROM branch_batch_stock ORDER BY batch_id,branch_id').all()
const add = (db, quantity, batch = 900001, branch = 900001) => db.prepare('INSERT INTO branch_batch_stock(batch_id,branch_id,quantity) VALUES(?,?,?)').run(batch, branch, quantity)
const deactivate = db => db.exec('UPDATE product_batches SET is_active=0 WHERE id=900001')
const activate = (db, id = 900001) => db.prepare('UPDATE product_batches SET is_active=1 WHERE id=?').run(id)
const inactiveError = /Positive lot stock requires an active received lot/
let passed = 0
function check(name, fn) { fn(); passed++; console.log(`PASS ${name}`) }

check('LF-only migration applies to a fresh full schema without changing data', () => {
  assert(!sql.includes('\r'))
  const db = new Database(schema)
  apply(db)
  assert.equal(db.prepare("SELECT COUNT(*) n FROM sqlite_master WHERE type='trigger' AND name LIKE '%0154'").get().n, 4)
  assert.equal(db.prepare('SELECT COUNT(*) n FROM product_batches').get().n, 0)
  assert.equal(db.prepare('PRAGMA integrity_check').get().integrity_check, 'ok')
  db.close()
})
check('positive insert to an inactive lot fails without metadata or quantity effects', () => {
  const db = fixture(), before = lot(db)
  assert.throws(() => add(db, 3), inactiveError)
  assert.deepEqual(lot(db), before)
  assert.deepEqual(qty(db), [])
  assert.equal(lot(db, 900002).is_active, 0)
  db.close()
})
check('explicit activation and restoration in one transaction preserves receipt metadata', () => {
  const db = fixture(), before = lot(db)
  db.transaction(() => { activate(db); add(db, 3) })()
  assert.deepEqual(lot(db), { ...before, is_active: 1 })
  assert.equal(qty(db)[0].quantity, 3)
  db.close()
})
check('zero insert stays inactive and a later positive update requires explicit activation', () => {
  const db = fixture()
  add(db, 0)
  assert.throws(() => db.exec('UPDATE branch_batch_stock SET quantity=2 WHERE batch_id=900001'), inactiveError)
  assert.equal(lot(db).is_active, 0)
  assert.equal(qty(db)[0].quantity, 0)
  db.transaction(() => {
    activate(db)
    db.exec('UPDATE branch_batch_stock SET quantity=2 WHERE batch_id=900001')
  })()
  assert.equal(qty(db)[0].quantity, 2)
  db.close()
})
check('UPSERT restoration fails while inactive and succeeds after explicit activation', () => {
  const db = fixture()
  add(db, 0)
  const upsert = () => db.exec('INSERT INTO branch_batch_stock(batch_id,branch_id,quantity) VALUES(900001,900001,4) ON CONFLICT(batch_id,branch_id) DO UPDATE SET quantity=quantity+excluded.quantity')
  assert.throws(upsert, inactiveError)
  assert.equal(lot(db).is_active, 0)
  assert.equal(qty(db)[0].quantity, 0)
  db.transaction(() => { activate(db); upsert() })()
  assert.equal(qty(db)[0].quantity, 4)
  db.close()
})
check('UPSERT conflict update cannot bypass the positive quantity guard with a zero insert', () => {
  const db = fixture()
  add(db, 0)
  assert.throws(() => db.exec('INSERT INTO branch_batch_stock(batch_id,branch_id,quantity) VALUES(900001,900001,0) ON CONFLICT(batch_id,branch_id) DO UPDATE SET quantity=quantity+3'), inactiveError)
  assert.equal(qty(db)[0].quantity, 0)
  assert.equal(lot(db).is_active, 0)
  db.close()
})
check('INSERT OR REPLACE to inactive lot fails and preserves the original stock row', () => {
  const db = fixture()
  add(db, 0)
  const before = db.prepare('SELECT * FROM branch_batch_stock').all()
  const replace = () => db.exec('INSERT OR REPLACE INTO branch_batch_stock(batch_id,branch_id,quantity) VALUES(900001,900001,3)')
  assert.throws(replace, inactiveError)
  assert.deepEqual(db.prepare('SELECT * FROM branch_batch_stock').all(), before)
  assert.equal(lot(db).is_active, 0)
  db.transaction(() => { activate(db); replace() })()
  assert.equal(qty(db)[0].quantity, 3)
  db.close()
})
check('moving a positive row to an inactive lot fails until explicitly activated', () => {
  const db = fixture()
  activate(db)
  add(db, 2)
  const before = qty(db)
  const move = () => db.exec('UPDATE branch_batch_stock SET batch_id=900002 WHERE batch_id=900001')
  assert.throws(move, inactiveError)
  assert.deepEqual(qty(db), before)
  assert.equal(lot(db, 900002).is_active, 0)
  db.transaction(() => { activate(db, 900002); move() })()
  assert.equal(lot(db, 900002).is_active, 1)
  deactivate(db)
  assert.equal(lot(db).is_active, 0)
  db.close()
})
check('deactivation is rejected while any branch retains positive stock', () => {
  const db = fixture()
  add(db, 0)
  assert.throws(() => add(db, 0.25, 900001, 900002), inactiveError)
  activate(db)
  add(db, 0.25, 900001, 900002)
  const before = lot(db), stock = qty(db)
  assert.throws(() => deactivate(db), /Cannot deactivate/)
  assert.deepEqual(lot(db), before)
  assert.deepEqual(qty(db), stock)
  db.exec('UPDATE branch_batch_stock SET quantity=0 WHERE batch_id=900001')
  deactivate(db)
  assert.equal(lot(db).is_active, 0)
  db.close()
})
check('NULL and noncanonical flags cannot hide positive stock', () => {
  const db = fixture()
  activate(db)
  add(db, 1)
  for (const flag of ['NULL', '2']) assert.throws(() => db.exec(`UPDATE product_batches SET is_active=${flag} WHERE id=900001`), /Cannot deactivate/)
  assert.equal(lot(db).is_active, 1)
  db.close()
})
check('INSERT OR REPLACE cannot bypass deactivation rejection or erase original receipt metadata', () => {
  const db = fixture()
  activate(db)
  add(db, 1)
  const before = lot(db)
  assert.throws(() => db.exec("INSERT OR REPLACE INTO product_batches(id,variant_product_id,batch_key,is_active) VALUES(900001,900001,'replacement',0)"), /Cannot deactivate/)
  assert.deepEqual(lot(db), before)
  db.close()
})
check('orphan positive inserts and lot reassignment fail atomically', () => {
  const db = fixture()
  assert.throws(() => add(db, 1, 999999), inactiveError)
  assert.deepEqual(qty(db), [])
  activate(db)
  add(db, 1)
  const before = qty(db)
  assert.throws(() => db.exec('UPDATE branch_batch_stock SET batch_id=999999 WHERE batch_id=900001'), inactiveError)
  assert.deepEqual(qty(db), before)
  db.close()
})
check('failed later stock statement rolls back earlier restoration and activation', () => {
  const db = fixture(), before = lot(db)
  assert.throws(() => db.transaction(() => { activate(db); add(db, 2); deactivate(db) })(), /Cannot deactivate/)
  assert.deepEqual(qty(db), [])
  assert.deepEqual(lot(db), before)
  db.close()
})
check('invalid multi-branch restoration rolls back earlier explicit activation and stock writes', () => {
  const db = fixture(), before = lot(db)
  assert.throws(() => db.transaction(() => {
    activate(db)
    add(db, 2)
    add(db, 1, 900002, 900002)
  })(), inactiveError)
  assert.deepEqual(qty(db), [])
  assert.deepEqual(lot(db), before)
  assert.equal(lot(db, 900002).is_active, 0)
  db.close()
})
check('preflight fails closed on existing inactive positive stock with no data or schema changes', () => {
  const db = fixture(false)
  add(db, 3)
  const before = db.serialize()
  assert.throws(() => apply(db), /0154_existing_positive_lots_require_active_parent_preflight/)
  assert.deepEqual(db.serialize(), before)
  db.close()
})
check('preflight fails closed on existing orphan positive stock', () => {
  const db = fixture(false)
  add(db, 1, 999999)
  assert.throws(() => apply(db), /0154_existing_positive_lots_require_active_parent_preflight/)
  assert.equal(qty(db)[0].quantity, 1)
  db.close()
})
check('preflight allows active positive stock and preserves zero-stock inactive history', () => {
  const db = fixture(false)
  db.exec('UPDATE product_batches SET is_active=1 WHERE id=900001')
  add(db, 5)
  add(db, 0, 900002)
  const before = [lot(db), lot(db, 900002)], stock = qty(db)
  apply(db)
  assert.deepEqual([lot(db), lot(db, 900002)], before)
  assert.deepEqual(qty(db), stock)
  db.close()
})
console.log(`${passed} positive-lot activation invariant checks passed`)
